-- ------------------------------------------------------------
-- NOVO SORTEIO V24
-- IMPORTANTE: NAO exclui vencedor anterior.
-- Assim a mesma pessoa continua no pool nos sorteios seguintes.
-- ------------------------------------------------------------
create or replace function public.staff_draw_raffle_v24(
  p_username text,
  p_password text,
  p_event_id bigint,
  p_prize text
)
returns table(
  draw_id bigint,
  winner_ticket_id bigint,
  customer_name text,
  ticket_code text,
  phone text,
  cpf text,
  promoter_code text,
  prize text,
  drawn_at timestamptz,
  source text
)
language plpgsql
security definer
set search_path=public,extensions
as $$
declare
  s public.staff_users%rowtype;
  e public.events%rowtype;
  d public.raffle_draws_v18%rowtype;

  v_source text;
  v_ticket_id bigint;
  v_manual_id bigint;
  v_name text;
  v_code text;
  v_phone text;
  v_cpf text;
  v_promoter text;
  v_prize text;
begin
  select u.* into s
  from public.staff_users u
  where u.username=trim(p_username)
    and u.active=true
    and u.password_hash=crypt(p_password,u.password_hash)
  limit 1;

  if not found or s.role<>'admin' then
    raise exception 'Sem permissao';
  end if;

  select ev.* into e
  from public.events ev
  where ev.id=p_event_id
  for update;

  if not found then
    raise exception 'Evento nao encontrado';
  end if;

  if not coalesce(e.raffle_enabled,false) then
    raise exception 'Ative o sorteio antes de sortear';
  end if;

  v_prize:=coalesce(nullif(trim(p_prize),''),nullif(trim(e.raffle_prize),''));
  if coalesce(v_prize,'')='' then
    raise exception 'Informe o premio do sorteio';
  end if;

  -- Cada ingresso pago gera 1 linha/chance.
  -- Cada participante manual gera N linhas conforme "chances".
  select
    pool.source,
    pool.ticket_id,
    pool.manual_id,
    pool.customer_name,
    pool.ticket_code,
    pool.phone,
    pool.cpf,
    pool.promoter_code
  into
    v_source,
    v_ticket_id,
    v_manual_id,
    v_name,
    v_code,
    v_phone,
    v_cpf,
    v_promoter
  from (
    select
      'ticket'::text as source,
      t.id::bigint as ticket_id,
      null::bigint as manual_id,
      t.customer_name::text,
      t.ticket_code::text,
      t.phone::text,
      t.cpf::text,
      t.promoter_code::text,
      1::integer as chance_no
    from public.tickets t
    where t.event_id=p_event_id
      and t.payment_status='Pago'

    union all

    select
      'manual'::text as source,
      null::bigint as ticket_id,
      m.id::bigint as manual_id,
      m.customer_name::text,
      ('MANUAL-'||m.id::text)::text as ticket_code,
      m.phone::text,
      null::text as cpf,
      null::text as promoter_code,
      gs::integer as chance_no
    from public.raffle_manual_participants_v24 m
    cross join lateral generate_series(1,m.chances) gs
    where m.event_id=p_event_id
      and m.active=true
  ) pool
  order by random()
  limit 1;

  if not found then
    raise exception 'Nenhum participante disponivel para o sorteio';
  end if;

  -- Mantem no evento o ultimo premio digitado.
  update public.events ev
  set raffle_prize=v_prize
  where ev.id=p_event_id;

  insert into public.raffle_draws_v18(
    event_id,
    winner_ticket_id,
    winner_manual_id,
    winner_name,
    winner_code,
    winner_phone,
    winner_promoter_code,
    winner_source,
    prize,
    drawn_by
  )
  values(
    p_event_id,
    v_ticket_id,
    v_manual_id,
    v_name,
    v_code,
    v_phone,
    v_promoter,
    v_source,
    v_prize,
    s.username
  )
  returning * into d;

  return query
  select
    d.id,
    v_ticket_id,
    v_name,
    v_code,
    v_phone,
    v_cpf,
    v_promoter,
    d.prize,
    d.drawn_at,
    v_source;
end;
$$;

grant execute on function public.staff_draw_raffle_v24(text,text,bigint,text)
to anon, authenticated;

