create or replace function public.public_lots_by_event_v16(p_event_id bigint)
returns table(
  id bigint, event_id bigint, name text, sector text, price numeric,
  price_female numeric, price_male numeric, quantity_total integer,
  quantity_sold bigint, quantity_available bigint, starts_at timestamptz,
  ends_at timestamptz, active boolean, sort_order integer,
  auto_sequence boolean, auto_locked boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  with lot_stats as (
    select l.*, count(t.id) filter (where t.payment_status in ('Pendente','Pago'))::bigint as sold
    from public.ticket_lots l
    left join public.tickets t on t.lot_id = l.id
    where l.event_id = p_event_id
    group by l.id
  )
  select l.id, l.event_id, l.name, l.sector,
         private.hype_effective_price((select base from public.ticket_lots base where base.id=l.id), 'Feminino', clock_timestamp()),
         private.hype_effective_price((select base from public.ticket_lots base where base.id=l.id), 'Feminino', clock_timestamp()),
         private.hype_effective_price((select base from public.ticket_lots base where base.id=l.id), 'Masculino', clock_timestamp()),
         l.quantity_total, l.sold,
         case when l.quantity_total = 0 then null else greatest(l.quantity_total - l.sold, 0)::bigint end,
         l.starts_at, l.ends_at, l.active, l.sort_order, l.auto_sequence,
         case when not l.auto_sequence then false else exists (
           select 1 from lot_stats earlier
           where earlier.event_id = l.event_id
             and lower(earlier.sector) = lower(l.sector)
             and earlier.active is true
             and (earlier.sort_order < l.sort_order or (earlier.sort_order = l.sort_order and earlier.id < l.id))
             and (earlier.quantity_total = 0 or earlier.sold < earlier.quantity_total)
         ) end
  from lot_stats l
  join public.events e on e.id = l.event_id
  where l.active is true and e.active is true
  order by l.sort_order, l.id;
$$;

