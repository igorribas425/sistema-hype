returns table(
  id bigint, event_id bigint, ticket_code text, qr_token text, customer_name text,
  phone text, email text, cpf text, gender text, lot_id bigint, lot_name text,
  sector text, price numeric, original_price numeric, discount_amount numeric,
  coupon_code text, promoter_code text, payment_status text, entry_status text,
  purchased_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lot public.ticket_lots%rowtype;
  v_event public.events%rowtype;
  c public.coupons_v16%rowtype;
  v_original numeric(12,2);
  v_discount numeric(12,2) := 0;
  v_service_fee numeric(12,2) := 1.98;
  v_final numeric(12,2);
  v_coupon_used bigint := 0;
  v_code text := upper(trim(coalesce(p_coupon_code, '')));
  v_promoter text := upper(trim(coalesce(p_promoter_code, '')));
  v_cpf text := nullif(regexp_replace(coalesce(p_cpf, ''), '[^0-9]', '', 'g'), '');
  v_id bigint;
  v_ticket_code text;
  v_qr text;
  v_purchased timestamptz;
  v_payment_status text := 'Pendente';
  v_payment_method text := 'PIX Asaas';
begin
  if length(trim(coalesce(p_name, ''))) < 2 then raise exception 'Nome do cliente é obrigatório'; end if;
  if position('@' in coalesce(p_email, '')) < 2 then raise exception 'E-mail inválido'; end if;
  if p_gender not in ('Feminino','Masculino') then raise exception 'Selecione Feminino ou Masculino'; end if;
  if v_cpf is not null and length(v_cpf) <> 11 then raise exception 'CPF precisa ter 11 números'; end if;

  select l.* into v_lot from public.ticket_lots l where l.id = p_lot_id for update;
  if not found or not private.hype_lot_available_at(v_lot, clock_timestamp()) then raise exception 'Categoria indisponível'; end if;
  select e.* into v_event from public.events e where e.id = v_lot.event_id for update;
  if not found or not v_event.active then raise exception 'Evento indisponível'; end if;

  if v_cpf is not null and v_event.max_tickets_per_cpf > 0 then
    perform pg_advisory_xact_lock(hashtextextended(v_event.id::text || ':' || v_cpf, 0));
    if (select count(*) from public.tickets t where t.event_id = v_event.id and t.cpf = v_cpf and t.payment_status in ('Pendente','Pago')) >= v_event.max_tickets_per_cpf then
      raise exception 'Limite de ingressos por CPF atingido';
    end if;
  end if;

  if v_lot.auto_sequence and exists (
    select 1 from public.ticket_lots earlier
    where earlier.event_id = v_lot.event_id and lower(earlier.sector) = lower(v_lot.sector)
      and earlier.active is true
      and (earlier.sort_order < v_lot.sort_order or (earlier.sort_order = v_lot.sort_order and earlier.id < v_lot.id))
      and (earlier.quantity_total = 0 or (select count(*) from public.tickets et where et.lot_id = earlier.id and et.payment_status in ('Pendente','Pago')) < earlier.quantity_total)
  ) then raise exception 'Este lote será liberado quando o anterior esgotar'; end if;

  v_original := private.hype_effective_price(v_lot, p_gender, clock_timestamp());
  if v_original = 0 then
    v_code := ''; v_service_fee := 0; v_final := 0;
    v_payment_status := 'Pago'; v_payment_method := p_gender || ' FREE';
  else
    if v_code <> '' then
      select x.* into c from public.coupons_v16 x
      where x.event_id = v_lot.event_id and x.code = v_code and x.active is true for update;
      if not found then raise exception 'Cupom inválido'; end if;
      if c.starts_at is not null and clock_timestamp() < c.starts_at then raise exception 'Cupom ainda não iniciou'; end if;
      if c.ends_at is not null and clock_timestamp() >= c.ends_at then raise exception 'Cupom expirado'; end if;
      select count(*) into v_coupon_used from public.tickets t
      where t.event_id = v_lot.event_id and upper(coalesce(t.coupon_code, '')) = v_code
        and t.payment_status in ('Pendente','Pago');
      if c.usage_limit > 0 and v_coupon_used >= c.usage_limit then raise exception 'Limite do cupom atingido'; end if;
      v_discount := case when c.discount_type = 'percent'
        then round(v_original * least(c.discount_value, 100) / 100, 2)
        else least(v_original, c.discount_value) end;
    end if;
    if v_original - v_discount <= 0 then raise exception 'O desconto precisa deixar saldo para pagamento'; end if;
    v_final := round(v_original - v_discount + v_service_fee, 2);
  end if;

  if v_promoter <> '' and not exists (
    select 1 from public.promoters_global_v16 p where p.code = v_promoter and p.active is true
  ) then raise exception 'Código de promoter inválido'; end if;

  loop
    v_ticket_code := 'HYPE-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 10));
    exit when not exists (select 1 from public.tickets t where t.ticket_code = v_ticket_code);
  end loop;
  v_qr := extensions.gen_random_uuid()::text;

  insert into public.tickets(
    event_id, lot_id, customer_name, phone, email, cpf, gender, price,
    original_price, discount_amount, service_fee, coupon_code, promoter_code,
    ticket_code, qr_token, payment_status, payment_method, paid_at
  ) values (
    v_lot.event_id, v_lot.id, trim(p_name), nullif(trim(p_phone), ''), lower(trim(p_email)),
    v_cpf, p_gender, v_final, v_original, v_discount, v_service_fee,
    nullif(v_code, ''), nullif(v_promoter, ''), v_ticket_code, v_qr,
    v_payment_status, v_payment_method,
    case when v_payment_status = 'Pago' then now() else null end
  ) returning tickets.id, tickets.purchased_at into v_id, v_purchased;

  return query select v_id, v_lot.event_id, v_ticket_code, v_qr, trim(p_name),
    nullif(trim(p_phone), ''), lower(trim(p_email)), v_cpf, p_gender,
    v_lot.id, v_lot.name, v_lot.sector, v_final, v_original, v_discount,
    nullif(v_code, ''), nullif(v_promoter, ''), v_payment_status,
    'Não utilizado'::text, v_purchased;
end;
$$;

