create or replace function public.staff_draw_raffle_v18(p_username text,p_password text,p_event_id bigint)
returns table(draw_id bigint,winner_ticket_id bigint,customer_name text,ticket_code text,phone text,cpf text,promoter_code text,prize text,drawn_at timestamptz)
language plpgsql security definer set search_path='' as $$
declare v_staff public.staff_users%rowtype; v_event public.events%rowtype; v_winner public.tickets%rowtype; v_draw public.raffle_draws_v18%rowtype;
begin
  v_staff:=private.hype_require_staff(p_username,p_password,array['admin']);
  select e.* into v_event from public.events e where e.id=p_event_id for update;
  if not found or not v_event.raffle_enabled then raise exception 'Ative o sorteio antes de sortear'; end if;
  if trim(v_event.raffle_prize)='' then raise exception 'Informe o prêmio'; end if;
  select t.* into v_winner from public.tickets t
  where t.event_id=p_event_id and t.payment_status='Pago'
    and not exists(
      select 1 from public.raffle_draws_v18 d
      where d.event_id=p_event_id and (
        d.winner_ticket_id=t.id
        or (regexp_replace(coalesce(t.cpf,''),'[^0-9]','','g')<>'' and regexp_replace(coalesce(d.winner_cpf,''),'[^0-9]','','g')=regexp_replace(coalesce(t.cpf,''),'[^0-9]','','g'))
        or (regexp_replace(coalesce(t.cpf,''),'[^0-9]','','g')='' and private.hype_name_key(d.winner_name)=private.hype_name_key(t.customer_name))
      )
    )
  order by random() limit 1;
  if not found then raise exception 'Nenhum participante disponível'; end if;
  insert into public.raffle_draws_v18(event_id,winner_ticket_id,winner_name,winner_code,winner_cpf,winner_phone,winner_promoter_code,prize,drawn_by)
  values(p_event_id,v_winner.id,v_winner.customer_name,v_winner.ticket_code,v_winner.cpf,v_winner.phone,v_winner.promoter_code,v_event.raffle_prize,v_staff.username)
  returning * into v_draw;
  return query select v_draw.id,v_winner.id,v_winner.customer_name,v_winner.ticket_code,v_winner.phone,v_winner.cpf,v_winner.promoter_code,v_draw.prize,v_draw.drawn_at;
end; $$;

