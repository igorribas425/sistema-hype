create or replace function public.staff_survey_report_v34(p_username text,p_password text,p_event_id bigint)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_result jsonb;
begin
  perform private.hype_require_staff(p_username,p_password,array['admin','gerente']);
  select jsonb_build_object(
    'eligible_count',(select count(*) from public.tickets t where t.event_id=p_event_id and t.payment_status='Pago' and t.entry_status='Entrada utilizada'),
    'invited_count',(select count(*) from public.event_survey_invites_v34 i where i.event_id=p_event_id and (i.sent_at is not null or i.email_sent_at is not null or i.whatsapp_sent_at is not null)),
    'response_count',count(r.id),'average_rating',coalesce(round(avg(r.rating)::numeric,2),0),
    'would_return_yes',count(r.id) filter(where r.would_return),'rating_1',count(r.id) filter(where r.rating=1),
    'rating_2',count(r.id) filter(where r.rating=2),'rating_3',count(r.id) filter(where r.rating=3),
    'rating_4',count(r.id) filter(where r.rating=4),'rating_5',count(r.id) filter(where r.rating=5),
    'comments',coalesce(jsonb_agg(jsonb_build_object('name',t.customer_name,'rating',r.rating,'would_return',r.would_return,'comment',r.comment,'submitted_at',r.submitted_at) order by r.submitted_at desc) filter(where r.id is not null),'[]'::jsonb)
  ) into v_result from public.event_survey_responses_v34 r left join public.tickets t on t.id=r.ticket_id where r.event_id=p_event_id;
  return coalesce(v_result,'{}'::jsonb);
end; $$;

