create or replace function public.public_quote_v16(
  p_lot_id bigint,
  p_gender text,
  p_coupon_code text default null
)
returns table(ok boolean, message text, original_price numeric, discount_amount numeric, final_price numeric, coupon_code text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lot public.ticket_lots%rowtype;
  c public.coupons_v16%rowtype;
  v_original numeric(12,2);
  v_discount numeric(12,2) := 0;
  v_coupon_used bigint := 0;
  v_code text := upper(trim(coalesce(p_coupon_code, '')));
begin
  select l.* into v_lot from public.ticket_lots l where l.id = p_lot_id;
  if not found or not private.hype_lot_available_at(v_lot, clock_timestamp()) then
    return query select false, 'Categoria indisponível', 0::numeric, 0::numeric, 0::numeric, null::text;
    return;
  end if;
  v_original := private.hype_effective_price(v_lot, p_gender, clock_timestamp());
  if v_original = 0 then
    return query select true, 'FREE até o horário configurado', 0::numeric, 0::numeric, 0::numeric, null::text;
    return;
  end if;
  if v_code = '' then
    return query select true, 'Sem cupom', v_original, 0::numeric, v_original, null::text;
    return;
  end if;

  select x.* into c from public.coupons_v16 x
  where x.event_id = v_lot.event_id and x.code = v_code and x.active is true;
  if not found then return query select false, 'Cupom inválido', v_original, 0::numeric, v_original, null::text; return; end if;
  if c.starts_at is not null and clock_timestamp() < c.starts_at then return query select false, 'Cupom ainda não iniciou', v_original, 0::numeric, v_original, null::text; return; end if;
  if c.ends_at is not null and clock_timestamp() >= c.ends_at then return query select false, 'Cupom expirado', v_original, 0::numeric, v_original, null::text; return; end if;
  select count(*) into v_coupon_used from public.tickets t
  where t.event_id = v_lot.event_id and upper(coalesce(t.coupon_code, '')) = v_code
    and t.payment_status in ('Pendente','Pago');
  if c.usage_limit > 0 and v_coupon_used >= c.usage_limit then
    return query select false, 'Limite do cupom atingido', v_original, 0::numeric, v_original, null::text;
    return;
  end if;
  v_discount := case when c.discount_type = 'percent'
    then round(v_original * least(c.discount_value, 100) / 100, 2)
    else least(v_original, c.discount_value) end;
  if v_original - v_discount <= 0 then
    return query select false, 'O desconto precisa deixar saldo para pagamento', v_original, v_discount, v_original, null::text;
    return;
  end if;
  return query select true, 'Cupom aplicado', v_original, v_discount, v_original - v_discount, c.code;
end;
$$;

create or replace function public.create_manual_order_v16(
  p_name text,
