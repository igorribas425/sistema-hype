create or replace function private.hype_name_key(p_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(
    translate(lower(trim(coalesce(p_name, ''))),
      'áàâãäéèêëíìîïóòôõöúùûüçñ',
      'aaaaaeeeeiiiiooooouuuucn'),
    '[^a-z0-9]+', '', 'g'
  );
$$;

create or replace function private.hype_effective_price(
  p_lot public.ticket_lots,
  p_gender text,
  p_at timestamptz
)
returns numeric
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_free_until timestamptz;
  v_price numeric(12,2);
begin
  if p_gender not in ('Feminino','Masculino') then
    raise exception 'Selecione Feminino ou Masculino';
  end if;
  v_price := case when p_gender = 'Masculino' then p_lot.price_male else p_lot.price_female end;
  select case when p_gender = 'Masculino' then r.male_free_until else r.female_free_until end
  into v_free_until
  from public.lot_free_rules_v38 r
  where r.lot_id = p_lot.id;
  if v_free_until is not null and p_at < v_free_until then return 0; end if;
  return coalesce(v_price, p_lot.price, 0);
end;
$$;

