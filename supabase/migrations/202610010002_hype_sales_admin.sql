create or replace function public.public_survey_submit_v34(p_token text,p_rating integer,p_would_return boolean,p_comment text)
returns boolean language plpgsql security definer set search_path='' as $$
declare v_invite public.event_survey_invites_v34%rowtype;
begin
  if p_rating is null or p_rating not between 1 and 5 then raise exception 'Escolha uma nota de 1 a 5'; end if;
  select i.* into v_invite from public.event_survey_invites_v34 i where i.token=p_token::uuid for update;
  if not found then raise exception 'Link da pesquisa inválido'; end if;
  if v_invite.responded_at is not null then raise exception 'Esta pesquisa já foi respondida'; end if;
  insert into public.event_survey_responses_v34(invite_token,event_id,ticket_id,rating,would_return,comment)
  values(v_invite.token,v_invite.event_id,v_invite.ticket_id,p_rating,coalesce(p_would_return,false),left(trim(coalesce(p_comment,'')),1200));
  update public.event_survey_invites_v34 set responded_at=now() where token=v_invite.token;
  return true;
exception when invalid_text_representation then raise exception 'Link da pesquisa inválido';
end; $$;

