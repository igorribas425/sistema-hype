create or replace function public.staff_upsert_coupon_v16(
  p_username text,p_password text,p_event_id bigint,p_id bigint,p_code text,
  p_discount_type text,p_discount_value numeric,p_usage_limit integer,
  p_starts_at timestamptz,p_ends_at timestamptz,p_active boolean
)
returns public.coupons_v16
language plpgsql security definer set search_path='' as $$
declare v_row public.coupons_v16%rowtype; v_code text:=upper(trim(p_code));
begin
  perform private.hype_require_staff(p_username,p_password,array['admin']);
  if v_code='' then raise exception 'Informe o código do cupom'; end if;
  if p_discount_type not in('percent','fixed') then raise exception 'Tipo de desconto inválido'; end if;
  if coalesce(p_discount_value,0)<0 or (p_discount_type='percent' and p_discount_value>100) then raise exception 'Desconto inválido'; end if;
  if coalesce(p_usage_limit,0)<0 then raise exception 'Limite inválido'; end if;
  if p_starts_at is not null and p_ends_at is not null and p_ends_at<=p_starts_at then raise exception 'Período inválido'; end if;
  if coalesce(p_id,0)=0 then
    insert into public.coupons_v16(event_id,code,discount_type,discount_value,usage_limit,starts_at,ends_at,active)
    values(p_event_id,v_code,p_discount_type,p_discount_value,coalesce(p_usage_limit,0),p_starts_at,p_ends_at,coalesce(p_active,true)) returning * into v_row;
  else
    update public.coupons_v16 c set code=v_code,discount_type=p_discount_type,discount_value=p_discount_value,
      usage_limit=coalesce(p_usage_limit,0),starts_at=p_starts_at,ends_at=p_ends_at,active=coalesce(p_active,true)
    where c.id=p_id and c.event_id=p_event_id returning * into v_row;
    if not found then raise exception 'Cupom não encontrado'; end if;
  end if;
  return v_row;
exception when unique_violation then raise exception 'Cupom já existe neste evento';
end; $$;

