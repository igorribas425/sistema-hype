-- HYPE V250 — rede de vendas: matrizes e filiais.
-- Aplicar SOMENTE após aprovação e teste do código, sem apagar cadastros ou ingressos.
-- Os códigos de venda existentes permanecem válidos.
create table if not exists public.promoter_branches_v250 (
  id bigint generated by default as identity primary key,
  matrix_id bigint not null references public.promoters_global_v16(id) on delete restrict,
  promoter_id bigint not null unique references public.promoters_global_v16(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint promoter_branches_v250_distinct check (matrix_id <> promoter_id)
);
create index if not exists promoter_branches_v250_matrix_id_idx
  on public.promoter_branches_v250(matrix_id);
alter table public.promoter_branches_v250 enable row level security;
revoke all on table public.promoter_branches_v250 from public, anon, authenticated;
revoke all on sequence public.promoter_branches_v250_id_seq from public, anon, authenticated;

-- Cadastro do vendedor pelo convite da matriz. Reusa todas as validações
-- (CPF, bloqueios, celular e geração de código) do cadastro oficial da Hype.
-- O CPF que já pertence a uma matriz ou outro promoter NÃO é transferido.
create or replace function public.public_promoter_branch_signup_v250(
  p_matrix_code text, p_name text, p_cpf text, p_phone text,
  p_website text default ''::text
)
returns table(ok boolean, message text, promoter_code text, sales_url text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cpf text := private.hype_digits_v49(p_cpf);
  v_matrix_id bigint;
  v_existing public.promoters_global_v16%rowtype;
  v_result record;
  v_seller_id bigint;
begin
  if trim(coalesce(p_website,'')) <> '' then
    return query select false, 'Não foi possível concluir o cadastro.', null::text, null::text;
    return;
  end if;

  select p.id into v_matrix_id
  from public.promoters_global_v16 p
  where p.code = upper(trim(coalesce(p_matrix_code,'')))
    and p.active is true
    and not exists (
      select 1 from public.promoter_branches_v250 b where b.promoter_id = p.id
    );
  if v_matrix_id is null then
    return query select false, 'Link de matriz inválido ou desativado.', null::text, null::text;
    return;
  end if;

  -- Mesmo lock do cadastro normal para impedir dupla atribuição simultânea.
  perform pg_advisory_xact_lock(hashtextextended('hype-promoter-cpf:' || v_cpf, 0));
  select p.* into v_existing
  from public.promoters_global_v16 p where p.cpf = v_cpf for update;

  if found then
    if v_existing.active and exists (
      select 1 from public.promoter_branches_v250 b
      where b.promoter_id = v_existing.id and b.matrix_id = v_matrix_id
    ) then
      return query select true, 'Seu link de vendas já está pronto.',
        v_existing.code, 'https://hypeloungeclub.com.br/cliente.html?promoter=' || v_existing.code;
    else
      return query select false,
        'CPF já cadastrado. Procure o administrador para verificar o vínculo.',
        null::text, null::text;
    end if;
    return;
  end if;

  select * into v_result
  from public.public_promoter_registration_submit_v49(p_name, p_cpf, p_phone, p_website);
  if not coalesce(v_result.ok,false) then
    return query select false, coalesce(v_result.message,'Cadastro indisponível.'),
      null::text, null::text;
    return;
  end if;

  select p.id into v_seller_id from public.promoters_global_v16 p
  where p.code = v_result.promoter_code;
  if v_seller_id is null then raise exception 'Não foi possível vincular o cadastro'; end if;
  insert into public.promoter_branches_v250 (matrix_id, promoter_id)
  values (v_matrix_id, v_seller_id);

  return query select true, 'Filial cadastrada. Seu link de vendas está pronto.',
    v_result.promoter_code::text, v_result.sales_url::text;
end;
$$;
revoke all on function public.public_promoter_branch_signup_v250(text,text,text,text,text) from public;
grant execute on function public.public_promoter_branch_signup_v250(text,text,text,text,text)
  to anon, authenticated;

-- Leitura exclusiva do administrador: filiais, matriz responsável e
-- vendas pagas. Não retorna CPF ou telefone ao frontend.
create or replace function public.staff_list_promoter_branches_v250(
  p_username text, p_password text
)
returns table(
  matrix_id bigint, promoter_id bigint,
  promoter_name text, promoter_code text, active boolean,
  sales_count bigint, paid_count bigint, revenue numeric
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.hype_require_staff(p_username, p_password, array['admin']);
  return query
  select
    b.matrix_id, p.id, p.name, p.code, p.active,
    count(t.id)::bigint,
    count(t.id) filter (where t.payment_status = 'Pago')::bigint,
    coalesce(sum(t.price) filter (where t.payment_status = 'Pago'),0)::numeric
  from public.promoter_branches_v250 b
  join public.promoters_global_v16 p on p.id = b.promoter_id
  left join public.tickets t
    on upper(t.promoter_code) = p.code
    and exists(select 1 from public.events e
               where e.id = t.event_id and e.active is true)
  group by b.matrix_id,p.id,p.name,p.code,p.active
  order by b.matrix_id, revenue desc, p.name;
end;
$$;
revoke all on function public.staff_list_promoter_branches_v250(text,text) from public;
grant execute on function public.staff_list_promoter_branches_v250(text,text) to anon, authenticated;
