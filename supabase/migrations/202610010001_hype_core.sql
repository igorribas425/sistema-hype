create or replace function private.hype_valid_cover_image(p_value text)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_payload text;
begin
  if coalesce(p_value, '') = '' then
    return true;
  end if;

  if octet_length(p_value) > 4 * 1024 * 1024 then
    return false;
  end if;

  if octet_length(p_value) <= 2048 and p_value ~ '^https://[^[:space:]]+$' then
    return true;
  end if;

  if p_value !~ '^data:image/(jpeg|png|webp);base64,[A-Za-z0-9+/]+={0,2}$' then
    return false;
  end if;

  v_payload := split_part(p_value, ',', 2);
  begin
    perform decode(v_payload, 'base64');
  exception when others then
    return false;
  end;
  return true;
end;
$$;

create table public.events (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 160),
  artist_name text not null default '',
  event_date date,
  opening_time time,
  closing_time time,
  venue text not null default '',
  description text not null default '',
  cover_image text not null default '',
  theme_color text not null default '' check (theme_color = '' or theme_color ~ '^#[0-9A-F]{6}$'),
  pix_key text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (private.hype_valid_cover_image(cover_image))
);

create table public.ticket_lots (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 120),
  sector text not null default 'Pista' check (length(trim(sector)) between 1 and 120),
  price numeric(12,2) not null default 0 check (price >= 0),
  price_female numeric(12,2) not null default 0 check (price_female >= 0),
  price_male numeric(12,2) not null default 0 check (price_male >= 0),
  quantity_total integer not null default 0 check (quantity_total >= 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  sort_order integer not null default 0,
  auto_sequence boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (starts_at is null or ends_at is null or ends_at > starts_at),
  check (not auto_sequence or quantity_total > 0)
);

