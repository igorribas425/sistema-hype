create or replace function public.staff_save_event_v13(
  p_username text,
  p_password text,
  p_event_id bigint,
  p_name text,
  p_artist_name text,
  p_event_date date,
  p_opening_time time,
  p_closing_time time,
  p_venue text,
  p_description text,
  p_cover_image text,
  p_active boolean,
  p_sort_order integer,
  p_theme_color text
)
returns public.events
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_staff public.staff_users%rowtype;
  v_event public.events%rowtype;
  v_color text := upper(trim(coalesce(p_theme_color, '')));
  v_cover text := coalesce(p_cover_image, '');
begin
  v_staff := private.hype_require_staff(p_username, p_password, array['admin','gerente']);
  if coalesce(trim(p_name), '') = '' then
    raise exception 'Nome do evento é obrigatório';
  end if;
  if v_color <> '' and v_color !~ '^#[0-9A-F]{6}$' then
    raise exception 'Cor do evento inválida. Use #RRGGBB';
  end if;
  if v_cover <> '' and not private.hype_valid_cover_image(v_cover) then
    raise exception 'Imagem inválida, corrompida, incompatível ou maior que 4 MB';
  end if;

  if coalesce(p_event_id, 0) = 0 then
    insert into public.events(
      name, artist_name, event_date, opening_time, closing_time, venue,
      description, cover_image, active, sort_order, theme_color
    ) values (
      trim(p_name), coalesce(trim(p_artist_name), ''), p_event_date,
      p_opening_time, p_closing_time, coalesce(trim(p_venue), ''),
      coalesce(trim(p_description), ''), v_cover, coalesce(p_active, true),
      coalesce(p_sort_order, 0), v_color
    ) returning * into v_event;
  else
    update public.events e
    set name = trim(p_name),
        artist_name = coalesce(trim(p_artist_name), ''),
        event_date = p_event_date,
        opening_time = p_opening_time,
        closing_time = p_closing_time,
        venue = coalesce(trim(p_venue), ''),
        description = coalesce(trim(p_description), ''),
        cover_image = case when v_cover = '' then e.cover_image else v_cover end,
        active = coalesce(p_active, true),
        sort_order = coalesce(p_sort_order, e.sort_order),
        theme_color = v_color
    where e.id = p_event_id
    returning * into v_event;
    if not found then raise exception 'Evento não encontrado'; end if;
  end if;

  insert into public.audit_logs(staff_user_id, action, metadata)
  values (v_staff.id, 'EVENTO_SALVO', jsonb_build_object('event_id', v_event.id));
  return v_event;
end;
$$;

