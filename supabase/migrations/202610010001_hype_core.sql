create or replace function private.hype_check_ticket_inventory()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lot public.ticket_lots%rowtype;
  v_used bigint;
begin
  if new.payment_status not in ('Pendente','Pago') then
    return new;
  end if;

  select l.* into v_lot
  from public.ticket_lots l
  where l.id = new.lot_id
  for update;

  if not found or new.event_id <> v_lot.event_id then
    raise exception 'Lote inválido para este evento';
  end if;
  if v_lot.quantity_total = 0 then
    return new;
  end if;

  select count(*) into v_used
  from public.tickets t
  where t.lot_id = new.lot_id
    and t.payment_status in ('Pendente','Pago')
    and (tg_op = 'INSERT' or t.id <> new.id);

  if v_used >= v_lot.quantity_total then
    raise exception 'Lote esgotado' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

