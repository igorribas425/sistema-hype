create or replace function public.staff_set_payment(
  p_username text,
  p_password text,
  p_ticket_id bigint,
  p_status text
)
returns public.tickets
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_staff public.staff_users%rowtype;
  v_ticket public.tickets%rowtype;
begin
  v_staff := private.hype_require_staff(p_username, p_password, array['admin','gerente','caixa']);
  if p_status not in ('Pendente','Pago','Cancelado') then raise exception 'Status inválido'; end if;
  update public.tickets t
  set payment_status = p_status,
      paid_at = case when p_status = 'Pago' then coalesce(t.paid_at, now()) else null end,
      canceled_at = case when p_status = 'Cancelado' then coalesce(t.canceled_at, now()) else null end
  where t.id = p_ticket_id
  returning * into v_ticket;
  if not found then raise exception 'Ingresso não encontrado'; end if;
  insert into public.audit_logs(staff_user_id, action, ticket_id, metadata)
  values (v_staff.id, 'PAGAMENTO_ALTERADO', v_ticket.id, jsonb_build_object('status', p_status));
  return v_ticket;
end;
$$;

