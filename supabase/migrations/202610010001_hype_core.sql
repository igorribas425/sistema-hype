create or replace function private.hype_password_hash(p_password text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
begin
  if length(coalesce(p_password, '')) < 12 then
    raise exception 'A senha deve ter pelo menos 12 caracteres';
  end if;
  return extensions.crypt(p_password, extensions.gen_salt('bf', 12));
end;
$$;

create or replace function private.hype_require_staff(
  p_username text,
  p_password text,
  p_roles text[] default null
)
returns public.staff_users
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_staff public.staff_users%rowtype;
begin
  select s.* into v_staff
  from public.staff_users s
  where s.username = lower(trim(p_username))
    and s.active is true
    and s.password_hash = extensions.crypt(p_password, s.password_hash)
  limit 1;

  if not found then
    raise exception 'Acesso negado' using errcode = '28000';
  end if;
  if p_roles is not null and not (v_staff.role = any(p_roles)) then
    raise exception 'Sem permissão' using errcode = '42501';
  end if;
  return v_staff;
end;
$$;

