create or replace function public.staff_list_lots_v16(
  p_username text,
  p_password text,
  p_event_id bigint
)
returns table(
  id bigint,
  event_id bigint,
  name text,
  sector text,
  price numeric,
  price_female numeric,
  price_male numeric,
  quantity_total integer,
  quantity_sold bigint,
  quantity_available bigint,
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean,
  sort_order integer,
  auto_sequence boolean,
  auto_locked boolean
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.hype_require_staff(p_username, p_password, array['admin','gerente']);
  return query
  with lot_stats as (
    select l.*,
           count(t.id) filter (where t.payment_status in ('Pendente','Pago'))::bigint as sold
    from public.ticket_lots l
    left join public.tickets t on t.lot_id = l.id
    where l.event_id = p_event_id
    group by l.id
  )
  select l.id, l.event_id, l.name, l.sector, l.price,
         l.price_female, l.price_male, l.quantity_total, l.sold,
         case when l.quantity_total = 0 then null
              else greatest(l.quantity_total - l.sold, 0)::bigint end,
         l.starts_at, l.ends_at, l.active, l.sort_order, l.auto_sequence,
         case when not l.auto_sequence then false else exists (
           select 1 from lot_stats earlier
           where earlier.event_id = l.event_id
             and lower(earlier.sector) = lower(l.sector)
             and earlier.active is true
             and (earlier.sort_order < l.sort_order or (earlier.sort_order = l.sort_order and earlier.id < l.id))
             and (earlier.quantity_total = 0 or earlier.sold < earlier.quantity_total)
         ) end
  from lot_stats l
  order by l.sort_order, l.id;
end;
$$;

create or replace function public.staff_upsert_lot_v16(
  p_username text,
  p_password text,
  p_event_id bigint,
  p_id bigint,
  p_name text,
  p_sector text,
  p_price_female numeric,
  p_price_male numeric,
  p_quantity_total integer,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_active boolean,
  p_sort_order integer,
  p_auto_sequence boolean
)
returns public.ticket_lots
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lot public.ticket_lots%rowtype;
begin
  perform private.hype_require_staff(p_username, p_password, array['admin','gerente']);
  if not exists (select 1 from public.events e where e.id = p_event_id) then
    raise exception 'Evento não encontrado';
  end if;
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_sector), '') = '' then
    raise exception 'Informe nome e setor do lote';
  end if;
  if coalesce(p_price_female, 0) < 0 or coalesce(p_price_male, 0) < 0 then
    raise exception 'Preço inválido';
  end if;
  if coalesce(p_quantity_total, 0) < 0 then raise exception 'Quantidade inválida'; end if;
  if coalesce(p_auto_sequence, false) and coalesce(p_quantity_total, 0) = 0 then
    raise exception 'Lote automático precisa ter estoque limitado';
  end if;
  if p_starts_at is not null and p_ends_at is not null and p_ends_at <= p_starts_at then
    raise exception 'O fim das vendas deve ser posterior ao início';
  end if;

  if coalesce(p_id, 0) = 0 then
    insert into public.ticket_lots(
      event_id, name, sector, price, price_female, price_male, quantity_total,
      starts_at, ends_at, active, sort_order, auto_sequence
    ) values (
      p_event_id, trim(p_name), trim(p_sector), coalesce(p_price_female, 0),
      coalesce(p_price_female, 0), coalesce(p_price_male, 0),
      coalesce(p_quantity_total, 0), p_starts_at, p_ends_at,
      coalesce(p_active, true), coalesce(p_sort_order, 0), coalesce(p_auto_sequence, false)
    ) returning * into v_lot;
  else
    update public.ticket_lots l
    set name = trim(p_name), sector = trim(p_sector),
        price = coalesce(p_price_female, 0),
        price_female = coalesce(p_price_female, 0),
        price_male = coalesce(p_price_male, 0),
        quantity_total = coalesce(p_quantity_total, 0),
        starts_at = p_starts_at, ends_at = p_ends_at,
        active = coalesce(p_active, true),
        sort_order = coalesce(p_sort_order, l.sort_order),
        auto_sequence = coalesce(p_auto_sequence, false)
    where l.id = p_id and l.event_id = p_event_id
    returning * into v_lot;
    if not found then raise exception 'Lote não encontrado neste evento'; end if;
  end if;
  return v_lot;
end;
$$;

