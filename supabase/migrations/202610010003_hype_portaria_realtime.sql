create or replace function public.portaria_device_validate_v18(p_device_key text,p_event_id bigint,p_code text)
returns table(
  ok boolean,message text,ticket_id bigint,event_id bigint,ticket_code text,customer_name text,cpf text,
  lot_name text,sector text,payment_status text,entry_status text,entry_at timestamptz,
  document_checked boolean,temporary_exit boolean,reentry_authorized boolean,reentry_count integer
)
language plpgsql security definer set search_path='' as $$
declare v_device uuid:=private.hype_device_id(p_device_key); v_ticket public.tickets%rowtype; v_lot public.ticket_lots%rowtype; v_code text:=regexp_replace(trim(coalesce(p_code,'')),'^#','','');
begin
  if v_device is null then raise exception 'Computador não autorizado'; end if;
  select t.* into v_ticket from public.tickets t
  where t.ticket_code=v_code or upper(t.ticket_code)=upper(v_code) or t.qr_token=v_code for update;
  if not found or v_ticket.event_id<>p_event_id then
    return query select false,'INGRESSO NÃO ENCONTRADO NESTE EVENTO',null::bigint,null::bigint,null::text,null::text,null::text,null::text,null::text,null::text,null::text,null::timestamptz,false,false,false,0; return;
  end if;
  select l.* into v_lot from public.ticket_lots l where l.id=v_ticket.lot_id;
  if v_ticket.payment_status<>'Pago' then
    return query select false,case when v_ticket.payment_status='Cancelado' then 'INGRESSO CANCELADO' else 'PAGAMENTO NÃO CONFIRMADO' end,
      v_ticket.id,v_ticket.event_id,v_ticket.ticket_code,v_ticket.customer_name,v_ticket.cpf,v_lot.name,v_lot.sector,v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at,
      v_ticket.document_checked,v_ticket.temporary_exit,v_ticket.reentry_authorized,v_ticket.reentry_count; return;
  end if;
  if v_ticket.entry_status='Entrada utilizada' and not v_ticket.temporary_exit then
    return query select false,'INGRESSO JÁ UTILIZADO',v_ticket.id,v_ticket.event_id,v_ticket.ticket_code,v_ticket.customer_name,v_ticket.cpf,v_lot.name,v_lot.sector,
      v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at,v_ticket.document_checked,v_ticket.temporary_exit,v_ticket.reentry_authorized,v_ticket.reentry_count; return;
  end if;
  if v_ticket.entry_status='Saída temporária' and not v_ticket.reentry_authorized then
    return query select false,'REENTRADA NÃO AUTORIZADA',v_ticket.id,v_ticket.event_id,v_ticket.ticket_code,v_ticket.customer_name,v_ticket.cpf,v_lot.name,v_lot.sector,
      v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at,v_ticket.document_checked,v_ticket.temporary_exit,v_ticket.reentry_authorized,v_ticket.reentry_count; return;
  end if;
  if v_ticket.entry_status='Reentrada autorizada' or (v_ticket.temporary_exit and v_ticket.reentry_authorized) then
    update public.tickets t set entry_status='Entrada utilizada',temporary_exit=false,reentry_authorized=false,
      reentry_count=t.reentry_count+1,last_entry_device=v_device::text where t.id=v_ticket.id returning * into v_ticket;
    perform private.hype_portaria_log(v_device,v_ticket.id,'REENTRY');
    return query select true,'REENTRADA LIBERADA',v_ticket.id,v_ticket.event_id,v_ticket.ticket_code,v_ticket.customer_name,v_ticket.cpf,v_lot.name,v_lot.sector,
      v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at,v_ticket.document_checked,v_ticket.temporary_exit,v_ticket.reentry_authorized,v_ticket.reentry_count; return;
  end if;
  update public.tickets t set entry_status='Entrada utilizada',entry_at=now(),entry_device=v_device::text,last_entry_device=v_device::text
  where t.id=v_ticket.id returning * into v_ticket;
  perform private.hype_portaria_log(v_device,v_ticket.id,'ENTRY');
  return query select true,'ENTRADA LIBERADA',v_ticket.id,v_ticket.event_id,v_ticket.ticket_code,v_ticket.customer_name,v_ticket.cpf,v_lot.name,v_lot.sector,
    v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at,v_ticket.document_checked,v_ticket.temporary_exit,v_ticket.reentry_authorized,v_ticket.reentry_count;
end; $$;

