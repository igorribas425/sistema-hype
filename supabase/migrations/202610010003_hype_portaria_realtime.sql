create or replace function private.hype_portaria_dashboard(p_event_id bigint)
returns jsonb language sql security definer stable set search_path='' as $$
  with paid as (
    select t.*,l.sector from public.tickets t join public.ticket_lots l on l.id=t.lot_id
    where t.event_id=p_event_id and t.payment_status='Pago'
  ), sectors as (
    select sector,count(*)::bigint paid,count(*) filter(where entry_status='Entrada utilizada')::bigint entered
    from paid group by sector
  ), recent as (
    select customer_name as name,sector,ticket_code as code,entry_at from paid
    where entry_status='Entrada utilizada' and entry_at is not null order by entry_at desc limit 12
  )
  select jsonb_build_object(
    'total_paid',(select count(*) from paid),
    'entered_count',(select count(*) from paid where entry_status='Entrada utilizada' and not temporary_exit),
    'remaining_count',(select count(*) from paid where entry_status<>'Entrada utilizada' or temporary_exit),
    'female_entered',(select count(*) from paid where entry_status='Entrada utilizada' and not temporary_exit and gender='Feminino'),
    'male_entered',(select count(*) from paid where entry_status='Entrada utilizada' and not temporary_exit and gender='Masculino'),
    'sector_stats',coalesce((select jsonb_agg(to_jsonb(s) order by sector) from sectors s),'[]'::jsonb),
    'recent',coalesce((select jsonb_agg(to_jsonb(r) order by entry_at desc) from recent r),'[]'::jsonb)
  );
$$;

