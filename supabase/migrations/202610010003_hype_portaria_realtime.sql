returns boolean language plpgsql security definer set search_path='' as $$
begin
  perform private.hype_require_staff(p_username,p_password,array['admin']);
  update public.portaria_devices_v18 d set active=false,revoked_at=now() where d.id=p_device_id;
  if not found then raise exception 'Dispositivo não encontrado'; end if;
  update public.portaria_readers_v19 r set active=false,revoked_at=now() where r.device_id=p_device_id and r.active;
  update public.portaria_pairings_v18 p set active=false where p.device_id=p_device_id and p.active;
  update public.portaria_reader_links_v20 l set revoked_at=now() where l.device_id=p_device_id and l.revoked_at is null;
  return true;
end; $$;

