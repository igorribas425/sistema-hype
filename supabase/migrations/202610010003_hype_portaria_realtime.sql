returns boolean language plpgsql security definer set search_path='' as $$
declare v_staff public.staff_users%rowtype;
begin
  v_staff:=private.hype_require_staff(p_username,p_password,array['admin']);
  update public.portaria_devices_v18 d set active=true,approved_at=now(),approved_by=v_staff.username,revoked_at=null,
