create or replace function private.hype_submit_reader_scan(p_reader_secret text,p_raw_code text)
returns public.portaria_scan_queue_v18
language plpgsql security definer set search_path='' as $$
declare v_reader public.portaria_readers_v19%rowtype; v_queue public.portaria_scan_queue_v18%rowtype; v_code text:=left(trim(coalesce(p_raw_code,'')),500);
begin
  if v_code='' then raise exception 'QR vazio'; end if;
  select r.* into v_reader from public.portaria_readers_v19 r
  join public.portaria_devices_v18 d on d.id=r.device_id
  where r.reader_secret_hash=extensions.digest(convert_to(p_reader_secret,'utf8'),'sha256')
    and r.active and r.revoked_at is null and (r.expires_at is null or r.expires_at>clock_timestamp())
    and d.active and d.revoked_at is null
  for update of r limit 1;
  if not found then raise exception 'Acesso do leitor encerrado'; end if;
  insert into public.portaria_scan_queue_v18(device_id,reader_id,raw_code)
  values(v_reader.device_id,v_reader.id,v_code) returning * into v_queue;
  update public.portaria_readers_v19 r set last_scan_at=now() where r.id=v_reader.id;
  return v_queue;
end; $$;

