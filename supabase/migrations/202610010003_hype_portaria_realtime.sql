create or replace function private.hype_claim_pair(
  p_pair_token text,p_reader_secret text,p_reader_label text,p_expires interval
) returns public.portaria_readers_v19
language plpgsql security definer set search_path='' as $$
declare v_pair public.portaria_pairings_v18%rowtype; v_device public.portaria_devices_v18%rowtype; v_reader public.portaria_readers_v19%rowtype;
begin
  if length(trim(coalesce(p_reader_secret,'')))<20 then raise exception 'Leitor inválido'; end if;
  select p.* into v_pair from public.portaria_pairings_v18 p
  where p.pair_token_hash=extensions.digest(convert_to(p_pair_token,'utf8'),'sha256')
    and p.active and p.claimed_at is null and p.expires_at>clock_timestamp()
  for update limit 1;
  if not found then raise exception 'QR de conexão expirado ou já utilizado'; end if;
  select d.* into v_device from public.portaria_devices_v18 d where d.id=v_pair.device_id;
  if not found or not v_device.active or v_device.revoked_at is not null then raise exception 'Computador não autorizado'; end if;
  insert into public.portaria_readers_v19(device_id,reader_secret_hash,reader_label,expires_at)
  values(v_pair.device_id,extensions.digest(convert_to(p_reader_secret,'utf8'),'sha256'),
    left(coalesce(nullif(trim(p_reader_label),''),nullif(trim(v_pair.reader_label),''),'Celular leitor'),50),now()+p_expires)
  returning * into v_reader;
  update public.portaria_pairings_v18 p set claimed_at=now(),reader_id=v_reader.id,active=false where p.id=v_pair.id;
  return v_reader;
end; $$;

