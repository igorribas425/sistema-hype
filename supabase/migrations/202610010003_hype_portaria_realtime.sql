create or replace function public.portaria_device_request_v18(p_device_key text,p_label text default null)
returns table(device_id uuid,request_code text,active boolean,label text,approved_at timestamptz,created_at timestamptz)
language plpgsql security definer set search_path='' as $$
declare v_hash bytea; v_row public.portaria_devices_v18%rowtype; v_code text;
begin
  if length(trim(coalesce(p_device_key,'')))<20 then raise exception 'Chave do dispositivo inválida'; end if;
  v_hash:=extensions.digest(convert_to(p_device_key,'utf8'),'sha256');
  select d.* into v_row from public.portaria_devices_v18 d where d.device_key_hash=v_hash;
  if found then
    if trim(coalesce(p_label,''))<>'' then
      update public.portaria_devices_v18 d set label=left(trim(p_label),80) where d.id=v_row.id returning * into v_row;
    end if;
    return query select v_row.id,v_row.request_code,(v_row.active and v_row.revoked_at is null),v_row.label,v_row.approved_at,v_row.created_at;
    return;
  end if;
  loop
    v_code:=upper(substr(replace(extensions.gen_random_uuid()::text,'-',''),1,8));
    exit when not exists(select 1 from public.portaria_devices_v18 d where d.request_code=v_code);
  end loop;
  insert into public.portaria_devices_v18(device_key_hash,request_code,label)
  values(v_hash,v_code,left(coalesce(nullif(trim(p_label),''),'Computador da Portaria'),80)) returning * into v_row;
  return query select v_row.id,v_row.request_code,false,v_row.label,v_row.approved_at,v_row.created_at;
end; $$;

create or replace function public.portaria_device_status_v18(p_device_key text)
returns table(device_id uuid,request_code text,active boolean,label text,approved_at timestamptz,revoked_at timestamptz,last_seen timestamptz)
language plpgsql security definer set search_path='' as $$
declare v_hash bytea:=extensions.digest(convert_to(coalesce(p_device_key,''),'utf8'),'sha256'); v_row public.portaria_devices_v18%rowtype;
begin
  select d.* into v_row from public.portaria_devices_v18 d where d.device_key_hash=v_hash;
  if not found then return; end if;
  if v_row.active and v_row.revoked_at is null then
    update public.portaria_devices_v18 d set last_seen=now() where d.id=v_row.id returning * into v_row;
  end if;
  return query select v_row.id,v_row.request_code,(v_row.active and v_row.revoked_at is null),v_row.label,v_row.approved_at,v_row.revoked_at,v_row.last_seen;
end; $$;

