create or replace function private.hype_secret_hash(p_secret text)
returns bytea language sql immutable set search_path='' as $$
  select extensions.digest(convert_to(trim(coalesce(p_secret,'')),'utf8'),'sha256');
$$;

create or replace function private.hype_device_id(p_device_key text)
returns uuid language sql security definer stable set search_path='' as $$
  select d.id from public.portaria_devices_v18 d
  where length(trim(coalesce(p_device_key,'')))>=20
    and d.device_key_hash=extensions.digest(convert_to(p_device_key,'utf8'),'sha256')
    and d.active and d.revoked_at is null
  limit 1;
$$;

create or replace function private.hype_device_authorized(p_device_key text)
returns boolean language sql security definer stable set search_path='' as $$
  select exists(
    select 1 from public.portaria_devices_v18 d
    where d.device_key_hash=extensions.digest(convert_to(p_device_key,'utf8'),'sha256')
      and d.active and d.revoked_at is null
  );
$$;

create or replace function private.hype_reader_id(p_reader_secret text)
returns uuid language sql security definer stable set search_path='' as $$
  select r.id from public.portaria_readers_v19 r
  join public.portaria_devices_v18 d on d.id=r.device_id
  where length(trim(coalesce(p_reader_secret,'')))>=20
    and r.reader_secret_hash=extensions.digest(convert_to(p_reader_secret,'utf8'),'sha256')
    and r.active and r.revoked_at is null
    and (r.expires_at is null or r.expires_at>clock_timestamp())
    and d.active and d.revoked_at is null
  limit 1;
$$;

