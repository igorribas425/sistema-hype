-- Helper: autenticação da equipe. Senhas são armazenadas com bcrypt via crypt().
create or replace function public.verify_staff(p_username text, p_password text)
returns table(id bigint, name text, username text, role text)
language sql
security definer
set search_path = public, extensions
as $$
  select s.id, s.name, s.username, s.role
  from public.staff_users s
  where s.username = trim(p_username)
    and s.active = true
    and s.password_hash = crypt(p_password, s.password_hash)
  limit 1;
$$;

grant execute on function public.verify_staff(text,text) to anon, authenticated;

-- Consulta pública dos lotes disponíveis.
create or replace function public.public_lots()
returns table(
  id bigint,
  name text,
  sector text,
  price numeric,
  quantity_total integer,
  quantity_sold bigint,
  quantity_available bigint,
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean
)
language sql
security definer
set search_path = public
as $$
  select
    l.id,
    l.name,
    l.sector,
    l.price,
    l.quantity_total,
    count(t.id) filter (where t.payment_status in ('Pendente','Pago'))::bigint as quantity_sold,
    case when l.quantity_total = 0 then null
         else greatest(l.quantity_total - count(t.id) filter (where t.payment_status in ('Pendente','Pago')), 0)::bigint
    end as quantity_available,
    l.starts_at,
    l.ends_at,
    l.active
  from public.ticket_lots l
  left join public.tickets t on t.lot_id = l.id
  join public.events e on e.id = l.event_id and e.active = true
  where l.active = true
  group by l.id
  order by l.sort_order, l.id;
$$;

grant execute on function public.public_lots() to anon, authenticated;

-- Cria ingresso com trava transacional para não estourar o estoque em compras simultâneas.
create or replace function public.create_ticket(
  p_name text,
  p_phone text,
  p_cpf text,
  p_gender text,
  p_lot_id bigint
)
returns table(
  id bigint,
  ticket_code text,
  qr_token text,
  customer_name text,
  phone text,
  cpf text,
  gender text,
  lot_id bigint,
  lot_name text,
  sector text,
  price numeric,
  payment_status text,
  entry_status text,
  purchased_at timestamptz
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_lot public.ticket_lots%rowtype;
  v_event public.events%rowtype;
  v_used integer;
  v_ticket_id bigint;
  v_code text;
  v_qr text;
begin
  if coalesce(trim(p_name),'') = '' then
    raise exception 'Nome do cliente é obrigatório';
  end if;

  select * into v_lot
  from public.ticket_lots
  where id = p_lot_id and active = true
  for update;

  if not found then
    raise exception 'Lote indisponível';
  end if;

  select * into v_event from public.events where id = v_lot.event_id and active = true;
  if not found then raise exception 'Evento indisponível'; end if;

  if v_lot.starts_at is not null and now() < v_lot.starts_at then
    raise exception 'Este lote ainda não abriu';
  end if;
  if v_lot.ends_at is not null and now() >= v_lot.ends_at then
    raise exception 'Este lote já encerrou';
  end if;

  select count(*)::integer into v_used
  from public.tickets
  where lot_id = v_lot.id and payment_status in ('Pendente','Pago');

  if v_lot.quantity_total > 0 and v_used >= v_lot.quantity_total then
    raise exception 'Lote esgotado';
  end if;

  v_code := 'HYPE-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
  v_qr := gen_random_uuid()::text;

  insert into public.tickets(event_id, lot_id, customer_name, phone, cpf, gender, price, ticket_code, qr_token)
  values(v_lot.event_id, v_lot.id, trim(p_name), nullif(trim(p_phone),''), nullif(trim(p_cpf),''), nullif(trim(p_gender),''), v_lot.price, v_code, v_qr)
  returning tickets.id into v_ticket_id;

  return query
  select t.id, t.ticket_code, t.qr_token, t.customer_name, t.phone, t.cpf, t.gender,
         t.lot_id, l.name, l.sector, t.price, t.payment_status, t.entry_status, t.purchased_at
  from public.tickets t
  join public.ticket_lots l on l.id = t.lot_id
  where t.id = v_ticket_id;
end;
$$;

grant execute on function public.create_ticket(text,text,text,text,bigint) to anon, authenticated;

