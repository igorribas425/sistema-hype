create or replace function public.staff_set_payment(p_username text, p_password text, p_ticket_id bigint, p_status text)
returns public.tickets
language plpgsql
security definer
set search_path = public, extensions
as $$
declare v_staff public.staff_users%rowtype; v_ticket public.tickets%rowtype;
begin
  select * into v_staff from public.staff_users where username=trim(p_username) and active=true and password_hash=crypt(p_password,password_hash);
  if not found then raise exception 'Acesso negado'; end if;
  if v_staff.role not in ('admin','gerente','caixa') then raise exception 'Sem permissão'; end if;
  if p_status not in ('Pendente','Pago','Cancelado') then raise exception 'Status inválido'; end if;

  update public.tickets
  set payment_status=p_status,
      paid_at=case when p_status='Pago' then coalesce(paid_at,now()) else null end,
      canceled_at=case when p_status='Cancelado' then coalesce(canceled_at,now()) else null end
  where id=p_ticket_id
  returning * into v_ticket;
  if not found then raise exception 'Ingresso não encontrado'; end if;

  insert into public.audit_logs(staff_user_id, action, ticket_id, metadata)
  values(v_staff.id, 'ALTERAR_PAGAMENTO', v_ticket.id, jsonb_build_object('status',p_status));
  return v_ticket;
end; $$;

grant execute on function public.staff_set_payment(text,text,bigint,text) to anon, authenticated;

-- Validação ATÔMICA: duas portarias tentando o mesmo QR ao mesmo tempo não conseguem liberar duas vezes.
create or replace function public.staff_validate_entry(
  p_username text,
  p_password text,
  p_code text,
  p_device text default null
)
returns table(
  ok boolean,
  message text,
  ticket_id bigint,
  ticket_code text,
  customer_name text,
  lot_name text,
  sector text,
  price numeric,
  payment_status text,
  entry_status text,
  entry_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff public.staff_users%rowtype;
  v_ticket public.tickets%rowtype;
  v_lot text;
begin
  select * into v_staff from public.staff_users where username=trim(p_username) and active=true and password_hash=crypt(p_password,password_hash);
  if not found then raise exception 'Acesso negado'; end if;
  if v_staff.role not in ('admin','gerente','portaria') then raise exception 'Sem permissão'; end if;

  select t.* into v_ticket
  from public.tickets t
  where lower(t.ticket_code)=lower(trim(p_code)) or lower(t.qr_token)=lower(trim(p_code))
  for update;

  if not found then
    return query select false,'INGRESSO NÃO ENCONTRADO',null::bigint,null::text,null::text,null::text,null::text,null::numeric,null::text,null::text,null::timestamptz;
    return;
  end if;

  select name into v_lot from public.ticket_lots where id=v_ticket.lot_id;

  if v_ticket.payment_status='Cancelado' then
    return query select false,'INGRESSO CANCELADO',v_ticket.id,v_ticket.ticket_code,v_ticket.customer_name,v_lot,(select sector from ticket_lots where id=v_ticket.lot_id),v_ticket.price,v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at;
    return;
  end if;
  if v_ticket.payment_status<>'Pago' then
    return query select false,'PAGAMENTO NÃO CONFIRMADO',v_ticket.id,v_ticket.ticket_code,v_ticket.customer_name,v_lot,(select sector from ticket_lots where id=v_ticket.lot_id),v_ticket.price,v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at;
    return;
  end if;
  if v_ticket.entry_status='Entrada utilizada' then
    return query select false,'INGRESSO JÁ UTILIZADO',v_ticket.id,v_ticket.ticket_code,v_ticket.customer_name,v_lot,(select sector from ticket_lots where id=v_ticket.lot_id),v_ticket.price,v_ticket.payment_status,v_ticket.entry_status,v_ticket.entry_at;
    return;
  end if;

  update public.tickets
  set entry_status='Entrada utilizada', entry_at=now(), entry_by=v_staff.id, entry_device=coalesce(nullif(trim(p_device),''),'Portaria')
  where id=v_ticket.id;

  insert into public.audit_logs(staff_user_id, action, ticket_id, metadata)
  values(v_staff.id,'ENTRADA_LIBERADA',v_ticket.id,jsonb_build_object('device',p_device));

  return query
  select true,'ENTRADA LIBERADA',v_ticket.id,v_ticket.ticket_code,v_ticket.customer_name,v_lot,
         (select sector from ticket_lots where id=v_ticket.lot_id),v_ticket.price,'Pago','Entrada utilizada',now();
end; $$;

grant execute on function public.staff_validate_entry(text,text,text,text) to anon, authenticated;

