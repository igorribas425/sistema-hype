create extension if not exists pgcrypto;

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  name text not null,
  event_date date,
  opening_time time,
  closing_time time,
  venue text,
  pix_key text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.ticket_lots (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  name text not null,
  sector text not null default 'Pista',
  price numeric(12,2) not null check (price >= 0),
  quantity_total integer not null default 0 check (quantity_total >= 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.staff_users (
  id bigint generated by default as identity primary key,
  name text not null,
  username text not null unique,
  password_hash text not null,
  role text not null check (role in ('admin','gerente','caixa','portaria')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  lot_id bigint not null references public.ticket_lots(id) on delete restrict,
  customer_name text not null,
  phone text,
  cpf text,
  gender text,
  price numeric(12,2) not null check (price >= 0),
  ticket_code text not null unique,
  qr_token text not null unique,
  payment_status text not null default 'Pendente' check (payment_status in ('Pendente','Pago','Cancelado')),
  entry_status text not null default 'Não utilizado' check (entry_status in ('Não utilizado','Entrada utilizada')),
  purchased_at timestamptz not null default now(),
  paid_at timestamptz,
  entry_at timestamptz,
  entry_by bigint,
  entry_device text,
  canceled_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_ticket_lots_event on public.ticket_lots(event_id, active, sort_order);
create index if not exists idx_tickets_event on public.tickets(event_id, created_at desc);
create index if not exists idx_tickets_lot on public.tickets(lot_id);
create index if not exists idx_tickets_name on public.tickets(lower(customer_name));
create index if not exists idx_tickets_phone on public.tickets(phone);
create index if not exists idx_tickets_code on public.tickets(ticket_code);

alter table public.tickets
  drop constraint if exists tickets_entry_by_fkey;
alter table public.tickets
  add constraint tickets_entry_by_fkey
  foreign key (entry_by) references public.staff_users(id) on delete set null;

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  staff_user_id bigint references public.staff_users(id) on delete set null,
  action text not null,
  ticket_id bigint references public.tickets(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

