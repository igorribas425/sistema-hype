-- Lista para Admin/Caixa/Portaria.
create or replace function public.staff_list_tickets(p_username text, p_password text, p_search text default '')
returns table(
  id bigint,
  ticket_code text,
  customer_name text,
  phone text,
  cpf text,
  gender text,
  lot_id bigint,
  lot_name text,
  sector text,
  price numeric,
  payment_status text,
  entry_status text,
  purchased_at timestamptz,
  paid_at timestamptz,
  entry_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare v_role text; begin
  select role into v_role from public.verify_staff(p_username,p_password) limit 1;
  if v_role is null then raise exception 'Acesso negado'; end if;
  return query
  select t.id,t.ticket_code,t.customer_name,t.phone,t.cpf,t.gender,t.lot_id,l.name,l.sector,t.price,
         t.payment_status,t.entry_status,t.purchased_at,t.paid_at,t.entry_at
