  where coalesce(p_search,'')='' or lower(t.customer_name) like '%'||lower(p_search)||'%'
      or lower(t.ticket_code) like '%'||lower(p_search)||'%'
      or coalesce(t.phone,'') like '%'||p_search||'%'
  order by t.created_at desc;
end; $$;

