create or replace function public.staff_upsert_lot(
  p_username text,p_password text,p_id bigint,p_name text,p_sector text,p_price numeric,
  p_quantity_total integer,p_starts_at timestamptz,p_ends_at timestamptz,p_active boolean,p_sort_order integer
)
returns public.ticket_lots
language plpgsql security definer set search_path=public as $$
declare v_staff public.staff_users%rowtype; v_lot public.ticket_lots%rowtype; v_event_id bigint;
begin
  select * into v_staff from public.staff_users where username=trim(p_username) and active=true and password_hash=crypt(p_password,password_hash);
  if not found or v_staff.role not in ('admin','gerente') then raise exception 'Sem permissão'; end if;
  select id into v_event_id from public.events where active=true order by id limit 1;
  if v_event_id is null then raise exception 'Nenhum evento ativo'; end if;
  if coalesce(p_name,'')='' then raise exception 'Nome do lote é obrigatório'; end if;
  if p_price<0 or p_quantity_total<0 then raise exception 'Preço/quantidade inválidos'; end if;
  if p_starts_at is not null and p_ends_at is not null and p_ends_at<=p_starts_at then raise exception 'Horários inválidos'; end if;

  if coalesce(p_id,0)=0 then
    insert into public.ticket_lots(event_id,name,sector,price,quantity_total,starts_at,ends_at,active,sort_order)
    values(v_event_id,p_name,coalesce(nullif(p_sector,''),'Pista'),p_price,p_quantity_total,p_starts_at,p_ends_at,coalesce(p_active,true),coalesce(p_sort_order,0))
    returning * into v_lot;
  else
    update public.ticket_lots set name=p_name,sector=coalesce(nullif(p_sector,''),'Pista'),price=p_price,quantity_total=p_quantity_total,
      starts_at=p_starts_at,ends_at=p_ends_at,active=coalesce(p_active,true),sort_order=coalesce(p_sort_order,sort_order)
    where id=p_id returning * into v_lot;
    if not found then raise exception 'Lote não encontrado'; end if;
  end if;
  return v_lot;
end; $$;

grant execute on function public.staff_upsert_lot(text,text,bigint,text,text,numeric,integer,timestamptz,timestamptz,boolean,integer) to anon, authenticated;

