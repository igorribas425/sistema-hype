    return query select false,'CONFIRA O DOCUMENTO/CPF ANTES DE LIBERAR',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return;
  end if;
  if t.entry_status='Entrada utilizada' and not coalesce(t.temporary_exit,false) then
    return query select false,'INGRESSO JA UTILIZADO',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return;
