  end if;

  if coalesce(t.temporary_exit,false) and coalesce(t.reentry_authorized,false) then
    update public.tickets x
    set temporary_exit=false,reentry_authorized=false,reentry_count=coalesce(x.reentry_count,0)+1,last_entry_device=d.label
    where x.id=t.id returning * into t;
    insert into public.portaria_logs_v18(device_id,ticket_id,action,metadata) values(v_device,t.id,'REENTRY',jsonb_build_object('device',d.label));
    return query select true,'REENTRADA LIBERADA',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return;
  end if;

  update public.tickets x
  set entry_status='Entrada utilizada',entry_at=coalesce(x.entry_at,now()),last_entry_device=d.label
  where x.id=t.id returning * into t;
  insert into public.portaria_logs_v18(device_id,ticket_id,action,metadata) values(v_device,t.id,'ENTRY',jsonb_build_object('device',d.label));
  return query select true,'ENTRADA LIBERADA',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count;
