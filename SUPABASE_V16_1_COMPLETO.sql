drop function if exists public.staff_upsert_lot_v16(text,text,bigint,bigint,text,text,numeric,numeric,integer,timestamptz,timestamptz,boolean,integer,boolean);
create function public.staff_upsert_lot_v16(
  p_username text,
  p_password text,
  p_event_id bigint,
  p_id bigint,
  p_name text,
  p_sector text,
  p_price_female numeric,
  p_price_male numeric,
  p_quantity_total integer,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_active boolean,
  p_sort_order integer,
  p_auto_sequence boolean
)
returns public.ticket_lots
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff_users%rowtype;
  v_lot public.ticket_lots%rowtype;
begin
  select s.* into v_staff
  from public.staff_users s
  where s.username=trim(p_username)
    and s.active=true
    and s.password_hash=crypt(p_password,s.password_hash)
  limit 1;

  if not found or v_staff.role not in ('admin','gerente') then raise exception 'Sem permissao'; end if;
  if not exists(select 1 from public.events e where e.id=p_event_id) then raise exception 'Evento nao encontrado'; end if;
  if coalesce(trim(p_sector),'')='' then raise exception 'Informe a categoria/setor'; end if;
  if coalesce(p_price_female,0)<0 or coalesce(p_price_male,0)<0 then raise exception 'Preco invalido'; end if;
  if coalesce(p_quantity_total,0)<0 then raise exception 'Quantidade invalida'; end if;
  if coalesce(p_auto_sequence,false) and coalesce(p_quantity_total,0)=0 then
    raise exception 'Lote automatico precisa ter quantidade maior que zero';
  end if;
  if p_starts_at is not null and p_ends_at is not null and p_ends_at<=p_starts_at then
    raise exception 'A expiracao precisa ser depois do inicio';
  end if;

  if coalesce(p_id,0)=0 then
    insert into public.ticket_lots(
      event_id,name,sector,price,price_female,price_male,quantity_total,starts_at,ends_at,active,sort_order,auto_sequence
    ) values (
      p_event_id,coalesce(nullif(trim(p_name),''),'1o Lote'),trim(p_sector),
      coalesce(p_price_female,0),coalesce(p_price_female,0),coalesce(p_price_male,0),
      coalesce(p_quantity_total,0),p_starts_at,p_ends_at,coalesce(p_active,true),coalesce(p_sort_order,0),coalesce(p_auto_sequence,false)
    ) returning * into v_lot;
  else
    update public.ticket_lots l
    set name=coalesce(nullif(trim(p_name),''),l.name),
        sector=trim(p_sector),
        price=coalesce(p_price_female,0),
        price_female=coalesce(p_price_female,0),
        price_male=coalesce(p_price_male,0),
        quantity_total=coalesce(p_quantity_total,0),
        starts_at=p_starts_at,
        ends_at=p_ends_at,
        active=coalesce(p_active,true),
        sort_order=coalesce(p_sort_order,l.sort_order),
        auto_sequence=coalesce(p_auto_sequence,false)
    where l.id=p_id and l.event_id=p_event_id
    returning * into v_lot;
    if not found then raise exception 'Categoria nao encontrada neste evento'; end if;
  end if;

  return v_lot;
end;
$$;

grant execute on function public.staff_upsert_lot_v16(text,text,bigint,bigint,text,text,numeric,numeric,integer,timestamptz,timestamptz,boolean,integer,boolean) to anon, authenticated;

-- =============================================================
-- 7) Cotacao publica: calcula cupom no banco, sem confiar no JS.
-- =============================================================

drop function if exists public.public_quote_v16(bigint,text,text);
create function public.public_quote_v16(p_lot_id bigint, p_gender text, p_coupon_code text default null)
returns table(
  ok boolean,
  message text,
  original_price numeric,
  discount_amount numeric,
  final_price numeric,
  coupon_code text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_lot public.ticket_lots%rowtype;
  v_coupon public.coupons_v16%rowtype;
  v_original numeric(12,2);
  v_discount numeric(12,2) := 0;
  v_used bigint := 0;
  v_code text := upper(trim(coalesce(p_coupon_code,'')));
begin
  if p_gender not in ('Feminino','Masculino') then
    return query select false,'Selecione Feminino ou Masculino',0::numeric,0::numeric,0::numeric,null::text; return;
  end if;

  select * into v_lot from public.ticket_lots where id=p_lot_id and active=true;
  if not found then return query select false,'Categoria indisponivel',0::numeric,0::numeric,0::numeric,null::text; return; end if;

  v_original := case when p_gender='Masculino' then coalesce(v_lot.price_male,v_lot.price,0)
                     else coalesce(v_lot.price_female,v_lot.price,0) end;

  if v_code='' then
    return query select true,'Sem cupom',v_original,0::numeric,v_original,null::text; return;
  end if;

  select * into v_coupon
  from public.coupons_v16 c
  where c.event_id=v_lot.event_id and upper(c.code)=v_code and c.active=true
  limit 1;

  if not found then
    return query select false,'Cupom invalido',v_original,0::numeric,v_original,null::text; return;
  end if;
  if v_coupon.starts_at is not null and now()<v_coupon.starts_at then
    return query select false,'Cupom ainda nao iniciou',v_original,0::numeric,v_original,null::text; return;
  end if;
  if v_coupon.ends_at is not null and now()>=v_coupon.ends_at then
    return query select false,'Cupom expirado',v_original,0::numeric,v_original,null::text; return;
  end if;

  select count(*)::bigint into v_used
  from public.tickets t
  where t.event_id=v_lot.event_id
    and upper(coalesce(t.coupon_code,''))=v_code
    and t.payment_status in ('Pendente','Pago');

  if v_coupon.usage_limit>0 and v_used>=v_coupon.usage_limit then
    return query select false,'Limite do cupom atingido',v_original,0::numeric,v_original,null::text; return;
  end if;

  if v_coupon.discount_type='percent' then
    v_discount := round(v_original * least(v_coupon.discount_value,100) / 100, 2);
  else
    v_discount := least(v_original,v_coupon.discount_value);
  end if;

  if greatest(v_original-v_discount,0) <= 0 then
    return query select false,'O desconto precisa deixar um valor maior que zero para pagamento PIX',v_original,v_discount,v_original,null::text; return;
  end if;
  return query select true,'Cupom aplicado',v_original,v_discount,greatest(v_original-v_discount,0),v_coupon.code;
end;
$$;

grant execute on function public.public_quote_v16(bigint,text,text) to anon, authenticated;

