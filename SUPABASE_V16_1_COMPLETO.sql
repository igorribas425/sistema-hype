drop function if exists public.staff_upsert_promoter_v16(text,text,bigint,bigint,text,text,boolean);
create function public.staff_upsert_promoter_v16(p_username text,p_password text,p_event_id bigint,p_id bigint,p_name text,p_code text,p_active boolean)
returns public.promoters_v16
language plpgsql security definer set search_path=public,extensions as $$
declare v_staff public.staff_users%rowtype; v_row public.promoters_v16%rowtype; v_code text:=upper(trim(p_code));
begin
  select * into v_staff from public.staff_users where username=trim(p_username) and active=true and password_hash=crypt(p_password,password_hash);
  if not found or v_staff.role<>'admin' then raise exception 'Sem permissao'; end if;
  if coalesce(trim(p_name),'')='' or v_code='' then raise exception 'Informe nome e codigo do promoter'; end if;
  if coalesce(p_id,0)=0 then
    insert into public.promoters_v16(event_id,name,code,active) values(p_event_id,trim(p_name),v_code,coalesce(p_active,true)) returning * into v_row;
  else
    update public.promoters_v16 set name=trim(p_name),code=v_code,active=coalesce(p_active,true) where id=p_id and event_id=p_event_id returning * into v_row;
    if not found then raise exception 'Promoter nao encontrado'; end if;
  end if;
  return v_row;
exception when unique_violation then raise exception 'Este codigo de promoter ja existe neste evento';
