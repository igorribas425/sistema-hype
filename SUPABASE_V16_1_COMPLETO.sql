-- =============================================================
-- HYPE V16 - DASHBOARD + PROMOTERS + CUPONS + LOTES AUTOMATICOS
-- Execute UMA VEZ no Supabase > SQL Editor > New query > Run.
--
-- NAO apaga eventos, ingressos, lotes, usuarios ou pagamentos.
-- Mantem tickets.price como valor final cobrado pelo Asaas.
-- =============================================================

create extension if not exists pgcrypto;

-- 1) Novos campos, todos compativeis com o sistema atual.
alter table public.ticket_lots
  add column if not exists auto_sequence boolean not null default false;

alter table public.tickets
  add column if not exists original_price numeric(12,2),
  add column if not exists discount_amount numeric(12,2) not null default 0,
  add column if not exists coupon_code text,
  add column if not exists promoter_code text;

update public.tickets
set original_price = coalesce(original_price, price),
    discount_amount = coalesce(discount_amount, 0)
where original_price is null or discount_amount is null;

-- 2) Promoters por evento.
create table if not exists public.promoters_v16 (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  name text not null,
  code text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(event_id, code)
);

create index if not exists idx_promoters_v16_event on public.promoters_v16(event_id, active);

-- 3) Cupons por evento.
create table if not exists public.coupons_v16 (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  code text not null,
  discount_type text not null default 'percent' check (discount_type in ('percent','fixed')),
  discount_value numeric(12,2) not null default 0 check (discount_value >= 0),
  usage_limit integer not null default 0 check (usage_limit >= 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(event_id, code)
);

create index if not exists idx_coupons_v16_event on public.coupons_v16(event_id, active);

-- Nenhuma leitura direta das tabelas de gestao pelo navegador.
revoke all on public.promoters_v16, public.coupons_v16 from anon, authenticated;

