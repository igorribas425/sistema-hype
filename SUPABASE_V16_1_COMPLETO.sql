  p_username text,p_password text,p_event_id bigint,p_id bigint,p_code text,p_discount_type text,p_discount_value numeric,p_usage_limit integer,p_starts_at timestamptz,p_ends_at timestamptz,p_active boolean
)
returns public.coupons_v16
language plpgsql security definer set search_path=public,extensions as $$
declare v_staff public.staff_users%rowtype; v_row public.coupons_v16%rowtype; v_code text:=upper(trim(p_code));
begin
  select * into v_staff from public.staff_users where username=trim(p_username) and active=true and password_hash=crypt(p_password,password_hash);
  if not found or v_staff.role<>'admin' then raise exception 'Sem permissao'; end if;
  if v_code='' then raise exception 'Informe o codigo do cupom'; end if;
  if p_discount_type not in ('percent','fixed') then raise exception 'Tipo de desconto invalido'; end if;
  if coalesce(p_discount_value,0)<0 then raise exception 'Desconto invalido'; end if;
  if p_discount_type='percent' and p_discount_value>100 then raise exception 'Percentual maximo e 100'; end if;
  if coalesce(p_usage_limit,0)<0 then raise exception 'Limite invalido'; end if;
  if p_starts_at is not null and p_ends_at is not null and p_ends_at<=p_starts_at then raise exception 'Periodo do cupom invalido'; end if;
  if coalesce(p_id,0)=0 then
    insert into public.coupons_v16(event_id,code,discount_type,discount_value,usage_limit,starts_at,ends_at,active)
    values(p_event_id,v_code,p_discount_type,p_discount_value,coalesce(p_usage_limit,0),p_starts_at,p_ends_at,coalesce(p_active,true)) returning * into v_row;
