    where id=p_id and event_id=p_event_id returning * into v_row;
    if not found then raise exception 'Cupom nao encontrado'; end if;
  end if;
  return v_row;
exception when unique_violation then raise exception 'Este cupom ja existe neste evento';
end; $$;

