-- =============================================================
-- 4) Catalogo publico V16: traz bloqueio automatico por sequencia.
-- =============================================================

drop function if exists public.public_lots_by_event_v16(bigint);
create function public.public_lots_by_event_v16(p_event_id bigint)
returns table(
  id bigint,
  event_id bigint,
  name text,
  sector text,
  price numeric,
  price_female numeric,
  price_male numeric,
  quantity_total integer,
  quantity_sold bigint,
  quantity_available bigint,
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean,
  sort_order integer,
  auto_sequence boolean,
  auto_locked boolean
)
language sql
security definer
set search_path = public
as $$
  with lot_stats as (
    select
      l.*,
      count(t.id) filter (where t.payment_status in ('Pendente','Pago'))::bigint as sold
    from public.ticket_lots l
    left join public.tickets t on t.lot_id = l.id
    where l.event_id = p_event_id
    group by l.id
  )
  select
    l.id,
    l.event_id,
    l.name,
    l.sector,
    coalesce(l.price_female, l.price)::numeric as price,
    coalesce(l.price_female, l.price)::numeric as price_female,
    coalesce(l.price_male, l.price)::numeric as price_male,
    l.quantity_total,
    l.sold as quantity_sold,
    case when l.quantity_total = 0 then null
         else greatest(l.quantity_total - l.sold, 0)::bigint
    end as quantity_available,
    l.starts_at,
    l.ends_at,
    l.active,
    l.sort_order,
    coalesce(l.auto_sequence,false) as auto_sequence,
    case
      when coalesce(l.auto_sequence,false) = false then false
      else exists (
        select 1
        from lot_stats p
        where p.event_id = l.event_id
          and lower(coalesce(p.sector,'')) = lower(coalesce(l.sector,''))
          and p.active = true
          and (p.sort_order < l.sort_order or (p.sort_order = l.sort_order and p.id < l.id))
          and (p.quantity_total = 0 or p.sold < p.quantity_total)
      )
    end as auto_locked
  from lot_stats l
  join public.events e on e.id = l.event_id
  where l.active = true
    and e.active = true
  order by l.sort_order, l.id;
$$;

grant execute on function public.public_lots_by_event_v16(bigint) to anon, authenticated;

