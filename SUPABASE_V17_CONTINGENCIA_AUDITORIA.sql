create or replace function public.staff_validate_entry_v17(
  p_username text,p_password text,p_code text,p_device text default null,p_offline_sync boolean default false
) returns table(ok boolean,message text,id bigint,event_id bigint,ticket_code text,customer_name text,cpf text,lot_name text,sector text,
  payment_status text,entry_status text,entry_at timestamptz,document_checked boolean,temporary_exit boolean,reentry_authorized boolean,reentry_count integer)
language plpgsql security definer set search_path=public,extensions as $$
declare s public.staff_users%rowtype; t public.tickets%rowtype; l public.ticket_lots%rowtype; code text:=trim(coalesce(p_code,''));
begin
  s:=public.hype_staff_v17(p_username,p_password);
  if s.role not in ('admin','portaria') then raise exception 'Sem permissão'; end if;
  select * into t from public.tickets x where x.ticket_code=code or x.qr_token=code or ('#'||x.ticket_code)=code limit 1 for update;
  if not found then return query select false,'INGRESSO NÃO ENCONTRADO',null::bigint,null::bigint,null::text,null::text,null::text,null::text,null::text,null::text,null::text,null::timestamptz,false,false,false,0; return; end if;
  select * into l from public.ticket_lots where id=t.lot_id;
  if t.payment_status<>'Pago' then return query select false,'PAGAMENTO NÃO CONFIRMADO',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return; end if;
  if not t.document_checked then return query select false,'CONFIRA O DOCUMENTO/CPF ANTES DE LIBERAR',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return; end if;
  if t.entry_status='Entrada utilizada' and not t.temporary_exit then
    return query select false,'INGRESSO JÁ UTILIZADO',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return;
  end if;
  if t.temporary_exit and not t.reentry_authorized then
    return query select false,'REENTRADA NÃO AUTORIZADA',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return;
  end if;
  if t.temporary_exit and t.reentry_authorized then
    update public.tickets set temporary_exit=false,reentry_authorized=false,reentry_count=coalesce(reentry_count,0)+1,last_entry_device=p_device where id=t.id returning * into t;
    perform public.hype_log_v17(t.event_id,t.id,s.username,s.role,case when p_offline_sync then 'OFFLINE_REENTRY_SYNC' else 'REENTRY' end,jsonb_build_object('device',p_device));
    return query select true,'REENTRADA LIBERADA',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count; return;
  end if;
  update public.tickets set entry_status='Entrada utilizada',entry_at=coalesce(entry_at,now()),last_entry_device=p_device where id=t.id returning * into t;
  perform public.hype_log_v17(t.event_id,t.id,s.username,s.role,case when p_offline_sync then 'OFFLINE_ENTRY_SYNC' else 'ENTRY' end,jsonb_build_object('device',p_device));
  return query select true,'ENTRADA LIBERADA',t.id,t.event_id,t.ticket_code,t.customer_name,t.cpf,l.name,l.sector,t.payment_status,t.entry_status,t.entry_at,t.document_checked,t.temporary_exit,t.reentry_authorized,t.reentry_count;
end; $$;
grant execute on function public.staff_validate_entry_v17(text,text,text,text,boolean) to anon,authenticated;

