create or replace function public.staff_event_summary_v17(p_username text,p_password text,p_event_id bigint)
returns jsonb language plpgsql security definer set search_path=public,extensions as $$
declare s public.staff_users%rowtype; r jsonb;
begin
 s:=public.hype_staff_v17(p_username,p_password);
 if s.role not in ('admin','gerente','caixa') then raise exception 'Sem permissão'; end if;
 select jsonb_build_object(
   'event_id',e.id,'event_name',e.name,'event_date',e.event_date,'closed_at',e.closed_at,
   'sold',count(t.id) filter(where t.payment_status='Pago'),
   'revenue',coalesce(sum(t.price) filter(where t.payment_status='Pago'),0),
   'entered',count(t.id) filter(where t.payment_status='Pago' and t.entry_status='Entrada utilizada'),
   'not_entered',count(t.id) filter(where t.payment_status='Pago' and t.entry_status<>'Entrada utilizada'),
   'canceled',count(t.id) filter(where t.payment_status='Cancelado'),
   'female',count(t.id) filter(where t.payment_status='Pago' and t.gender='Feminino'),
   'male',count(t.id) filter(where t.payment_status='Pago' and t.gender='Masculino'),
   'reentries',coalesce(sum(t.reentry_count),0),
   'temporary_out',count(t.id) filter(where t.temporary_exit=true)
 ) into r from public.events e left join public.tickets t on t.event_id=e.id where e.id=p_event_id group by e.id;
 return coalesce(r,'{}'::jsonb);
end; $$;
grant execute on function public.staff_event_summary_v17(text,text,bigint) to anon,authenticated;

