create table if not exists public.hype_action_logs_v17 (
  id bigint generated by default as identity primary key,
  event_id bigint references public.events(id) on delete set null,
  ticket_id bigint references public.tickets(id) on delete set null,
  actor_username text,
  actor_role text,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_hype_logs_event on public.hype_action_logs_v17(event_id, created_at desc);
create index if not exists idx_hype_logs_ticket on public.hype_action_logs_v17(ticket_id, created_at desc);
revoke all on public.hype_action_logs_v17 from anon, authenticated;

create or replace function public.hype_staff_v17(p_username text, p_password text)
returns public.staff_users
language plpgsql security definer set search_path=public,extensions as $$
declare v public.staff_users%rowtype;
begin
  select s.* into v from public.staff_users s
  where s.username=trim(p_username) and s.active=true
    and s.password_hash=crypt(p_password,s.password_hash)
  limit 1;
  if not found then raise exception 'Acesso negado'; end if;
  return v;
end; $$;

revoke all on function public.hype_staff_v17(text,text) from public;

create or replace function public.hype_log_v17(
  p_event_id bigint, p_ticket_id bigint, p_actor text, p_role text,
  p_action text, p_details jsonb default '{}'::jsonb
) returns void
language sql security definer set search_path=public as $$
  insert into public.hype_action_logs_v17(event_id,ticket_id,actor_username,actor_role,action,details)
  values(p_event_id,p_ticket_id,p_actor,p_role,p_action,coalesce(p_details,'{}'::jsonb));
$$;
revoke all on function public.hype_log_v17(bigint,bigint,text,text,text,jsonb) from public;

-- Bloqueio transacional por CPF quando o evento estiver com limite = 1.
create or replace function public.hype_block_duplicate_cpf_v17()
returns trigger
language plpgsql set search_path=public as $$
declare v_limit integer; v_cpf text;
begin
  select coalesce(e.max_tickets_per_cpf,0) into v_limit from public.events e where e.id=new.event_id;
  if v_limit = 1 then
    v_cpf := regexp_replace(coalesce(new.cpf,''),'\D','','g');
    if length(v_cpf) <> 11 then raise exception 'CPF obrigatório para este evento'; end if;
    if exists(
      select 1 from public.tickets t
      where t.event_id=new.event_id
        and regexp_replace(coalesce(t.cpf,''),'\D','','g')=v_cpf
        and t.payment_status in ('Pendente','Pago')
        and (tg_op='INSERT' or t.id<>new.id)
    ) then
      raise exception 'Este CPF já possui ingresso neste evento';
    end if;
  end if;
  return new;
end; $$;

drop trigger if exists trg_hype_duplicate_cpf_v17 on public.tickets;
create trigger trg_hype_duplicate_cpf_v17
before insert or update of cpf,event_id,payment_status on public.tickets
for each row execute function public.hype_block_duplicate_cpf_v17();

create or replace function public.staff_set_event_cpf_limit_v17(
  p_username text,p_password text,p_event_id bigint,p_limit_one boolean
) returns boolean
language plpgsql security definer set search_path=public,extensions as $$
declare s public.staff_users%rowtype;
begin
  s:=public.hype_staff_v17(p_username,p_password);
  if s.role not in ('admin','gerente') then raise exception 'Sem permissão'; end if;
  update public.events set max_tickets_per_cpf=case when p_limit_one then 1 else 0 end where id=p_event_id;
  perform public.hype_log_v17(p_event_id,null,s.username,s.role,'EVENT_CPF_LIMIT',jsonb_build_object('limit_one',p_limit_one));
  return true;
end; $$;
grant execute on function public.staff_set_event_cpf_limit_v17(text,text,bigint,boolean) to anon,authenticated;

create or replace function public.staff_mark_document_v17(
  p_username text,p_password text,p_ticket_id bigint,p_checked boolean
) returns boolean
language plpgsql security definer set search_path=public,extensions as $$
declare s public.staff_users%rowtype; t public.tickets%rowtype;
begin
  s:=public.hype_staff_v17(p_username,p_password);
  if s.role not in ('admin','portaria') then raise exception 'Sem permissão'; end if;
