-- Banco efêmero para validar exclusivamente a migração V250.
create schema if not exists private;
create role anon nologin;
create role authenticated nologin;
create table public.promoters_global_v16 (
  id bigint generated by default as identity primary key,
  name text not null, code text not null unique,
  active boolean not null default true,
  cpf text unique, phone text
);
create table public.events (
  id bigint generated by default as identity primary key,
  name text not null,
  active boolean not null default true
);
create table public.tickets (
  id bigint generated by default as identity primary key,
  event_id bigint references public.events(id),
  promoter_code text,
  payment_status text,
  price numeric,
  customer_name text,
  purchased_at timestamptz not null default now()
);
create function private.hype_digits_v49(p text)
returns text language sql immutable as $$
  select regexp_replace(coalesce(p,''), '[^0-9]', '', 'g')
$$;
create function private.hype_require_staff(
  p_username text, p_password text, p_roles text[]
) returns void language plpgsql as $$
begin
  if p_username <> 'admin-teste' or p_password <> 'senha-teste'
  then raise exception 'Sem permissão';
  end if;
end;
$$;
-- Simula a interface da RPC existente; NÃO substitui teste de integração Supabase.
create function public.public_promoter_registration_submit_v49(
  p_name text, p_cpf text, p_phone text, p_website text default ''
) returns table(ok boolean, message text, promoter_code text, sales_url text)
language plpgsql as $$
declare v_code text := 'FIL-' || private.hype_digits_v49(p_cpf);
begin
  if length(trim(coalesce(p_name,''))) < 2
     or length(private.hype_digits_v49(p_cpf)) <> 11
     or length(private.hype_digits_v49(p_phone)) not in (10,11)
     or coalesce(p_website,'') <> '' then
    return query select false, 'Dados inválidos', null::text, null::text;
    return;
  end if;
  insert into public.promoters_global_v16(name,code,cpf,phone)
  values(trim(p_name), v_code, private.hype_digits_v49(p_cpf),p_phone)
  on conflict (cpf) do nothing;
  return query select true, 'Cadastro efetuado', v_code,
    'https://hypeloungeclub.com.br/cliente.html?promoter=' || v_code;
end;
$$;
